<p>Векторные регистры <code>xmm</code> (128 бит), <code>ymm</code> (256 бит, AVX) и <code>zmm</code> (512 бит) хранят несколько чисел сразу, а SIMD-инструкции обрабатывают их одновременно. С флагом <code>-march=native</code> компилятор использует самые широкие инструкции твоего процессора.</p>
