<p>Простые типы, целиком живущие на стеке, реализуют <code>Copy</code>: целые, дробные, <code>bool</code>, <code>char</code>, кортежи и массивы из таких типов. Они копируются при присваивании. Типы, владеющие ресурсами (<code>String</code>, <code>Vec</code>, <code>Box</code>), только перемещаются; для копии вызывают <code>.clone()</code> — явно, потому что это может быть дорого.</p>
